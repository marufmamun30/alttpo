void ui_fill(int x, int y, int w, int h, uint32_t c) {
  if (x < 0) { w += x; x = 0; }
  if (y < 0) { h += y; y = 0; }
  if (x + w > CANVAS_W) w = CANVAS_W - x;
  if (y + h > CANVAS_H) h = CANVAS_H - y;
  if (w <= 0 || h <= 0) return;
  for (int j = 0; j < h; j++) {
    uint32_t *p = g_canvas + (y + j) * CANVAS_W + x;
    for (int i = 0; i < w; i++) p[i] = c;
  }
}

void ui_blend(int x, int y, int w, int h, uint32_t c, int alpha) {
  if (x < 0) { w += x; x = 0; }
  if (y < 0) { h += y; y = 0; }
  if (x + w > CANVAS_W) w = CANVAS_W - x;
  if (y + h > CANVAS_H) h = CANVAS_H - y;
  if (w <= 0 || h <= 0) return;
  uint32_t rb = (c & 0xff00ff) * alpha, g = (c & 0x00ff00) * alpha;
  int ia = 255 - alpha;
  for (int j = 0; j < h; j++) {
    uint32_t *p = g_canvas + (y + j) * CANVAS_W + x;
    for (int i = 0; i < w; i++) {
      uint32_t d = p[i];
      p[i] = ((((d & 0xff00ff) * ia + rb) >> 8) & 0xff00ff) | ((((d & 0x00ff00) * ia + g) >> 8) & 0x00ff00);
    }
  }
}

static void outline(int x, int y, int w, int h, uint32_t c) {
  ui_fill(x, y, w, 1, c); ui_fill(x, y + h - 1, w, 1, c);
  ui_fill(x, y, 1, h, c); ui_fill(x + w - 1, y, 1, h, c);
}

// A panel like the item menu boxes: dark blue glass with a gold double border.
void ui_frame(int x, int y, int w, int h) {
  ui_blend(x + 2, y + 2, w - 4, h - 4, COL_PANEL, 232);
  outline(x, y, w, h, 0x000000);
  outline(x + 1, y + 1, w - 2, h - 2, COL_GOLD_D);
  outline(x + 2, y + 2, w - 4, h - 4, COL_GOLD);
  outline(x + 3, y + 3, w - 6, h - 6, COL_GOLD_D);
  outline(x + 4, y + 4, w - 8, h - 8, 0x000000);
  // corner studs
  for (int i = 0; i < 4; i++) {
    int cx = (i & 1) ? x + w - 7 : x, cy = (i & 2) ? y + h - 7 : y;
    ui_fill(cx, cy, 7, 7, 0x000000);
    ui_fill(cx + 1, cy + 1, 5, 5, COL_GOLD);
    ui_fill(cx + 2, cy + 2, 3, 3, COL_GOLD_D);
    ui_fill(cx + 2, cy + 2, 1, 1, 0xFFF8C0);
  }
}

void ui_frame_titled(int x, int y, int w, int h, const char *title) {
  ui_frame(x, y, w, h);
  int tw = ui_text_w(title, 2) + 16;
  int tx = x + (w - tw) / 2;
  ui_fill(tx, y - 9, tw, 23, 0x000000);
  ui_fill(tx + 1, y - 8, tw - 2, 21, COL_GOLD_D);
  ui_fill(tx + 2, y - 7, tw - 4, 19, 0x182058);
  ui_text(tx + 8, y - 5, title, COL_GOLD, 2);
}

// letters that reach below the baseline use an eighth row
static const uint8_t kDescG[8] = {0x00,0x00,0x0F,0x11,0x11,0x0F,0x01,0x0E};
static const uint8_t kDescJ[8] = {0x02,0x00,0x06,0x02,0x02,0x02,0x12,0x0C};
static const uint8_t kDescP[8] = {0x00,0x00,0x1E,0x11,0x11,0x1E,0x10,0x10};
static const uint8_t kDescQ[8] = {0x00,0x00,0x0F,0x11,0x11,0x0F,0x01,0x01};
static const uint8_t kDescY[8] = {0x00,0x00,0x11,0x11,0x11,0x0F,0x01,0x0E};

static void glyph(int x, int y, unsigned char ch, uint32_t c, int scale) {
  if (ch < 32 || ch > 126) ch = '?';
  const uint8_t *g = kFont[ch - 32];
  int rows = 7;
  switch (ch) {
    case 'g': g = kDescG; rows = 8; break;
    case 'j': g = kDescJ; rows = 8; break;
    case 'p': g = kDescP; rows = 8; break;
    case 'q': g = kDescQ; rows = 8; break;
    case 'y': g = kDescY; rows = 8; break;
  }
  for (int r = 0; r < rows; r++) {
    uint8_t bits = g[r];
    if (!bits) continue;
    for (int col = 0; col < 5; col++)
      if (bits & (0x10 >> col)) ui_fill(x + col * scale, y + r * scale, scale, scale, c);
  }
}

int ui_text_w(const char *s, int scale) {
  return (int)strlen(s) * 6 * scale;
}

int ui_text_plain(int x, int y, const char *s, uint32_t c, int scale) {
  int x0 = x;
  for (; *s; s++, x += 6 * scale) glyph(x, y, (unsigned char)*s, c, scale);
  return x - x0;
}

// shadowed text, the way the game draws its menu text
int ui_text(int x, int y, const char *s, uint32_t c, int scale) {
  ui_text_plain(x + scale, y + scale, s, 0x000000, scale);
  if (scale == 1) {
    ui_text_plain(x + 1, y, s, 0x000000, 1);
    ui_text_plain(x, y + 1, s, 0x000000, 1);
    ui_text_plain(x - 1, y, s, 0x000000, 1);
    ui_text_plain(x, y - 1, s, 0x000000, 1);
  }
  return ui_text_plain(x, y, s, c, scale);
}

void ui_text_center(int cx, int y, const char *s, uint32_t c, int scale) {
  ui_text(cx - ui_text_w(s, scale) / 2, y, s, c, scale);
}

void ui_text_right(int rx, int y, const char *s, uint32_t c, int scale) {
  ui_text(rx - ui_text_w(s, scale), y, s, c, scale);
}

// word wrapped text, returns the height used
int ui_text_wrap(int x, int y, int w, const char *s, uint32_t c, int scale) {
  int maxc = w / (6 * scale);
  if (maxc < 1) maxc = 1;
  int y0 = y;
  char line[160];
  while (*s) {
    int n = 0, lastSpace = -1;
    while (s[n] && s[n] != '\n' && n < maxc && n < (int)sizeof(line) - 1) {
      if (s[n] == ' ') lastSpace = n;
      n++;
    }
    int take = n;
    if (s[n] && s[n] != '\n' && lastSpace > 0) take = lastSpace;
    memcpy(line, s, take);
    line[take] = 0;
    ui_text(x, y, line, c, scale);
    y += 9 * scale + 1;
    s += take;
    while (*s == ' ') s++;
    if (*s == '\n') s++;
  }
  return y - y0;
}

static void tri(int cx, int top, int size, uint32_t light, uint32_t mid, uint32_t dark) {
  // upward triangle, apex at (cx, top), "size" rows tall
  for (int r = 0; r < size; r++) {
    int half = r;
    ui_fill(cx - half, top + r, half * 2 + 1, 1, mid);
    ui_fill(cx - half, top + r, 1 + half / 3, 1, light);
    ui_fill(cx + half - half / 4, top + r, 1 + half / 4, 1, dark);
  }
  ui_fill(cx - size + 1, top + size - 1, size * 2 - 1, 1, dark);
}

void ui_triforce(int cx, int cy, int size) {
  int h = size / 2;
  tri(cx, cy - h, h, 0xFFF8A0, 0xF8D038, 0xB07818);
  tri(cx - h, cy, h, 0xFFF8A0, 0xF8D038, 0xB07818);
  tri(cx + h, cy, h, 0xFFF8A0, 0xF8D038, 0xB07818);
}

// the selection pointer: a little fairy, like the file select screen
void ui_cursor(int x, int y) {
  static const char *kFairy[2][11] = {
    {
      ".ww....ww....",
      "wbbw..wbbw...",
      "wbbbwwbbbw...",
      ".wbbbbbbw....",
      "..wwppww.....",
      "..wppppw.....",
      "...pyyp......",
      "...pyyp......",
      "....pp.......",
      "....rr.......",
      "...r..r......",
    },
    {
      ".............",
      ".ww....ww....",
      "wbbbwwbbbw...",
      "wbbbbbbbbw...",
      ".wwwppwww....",
      "..wppppw.....",
      "...pyyp......",
      "...pyyp......",
      "....pp.......",
      "....rr.......",
      "...r..r......",
    },
  };
  int f = (g_uiTick / 8) & 1;
  int bob = ((g_uiTick / 16) & 1);
  for (int r = 0; r < 11; r++) {
    const char *row = kFairy[f][r];
    for (int c = 0; row[c]; c++) {
      if (row[c] == '.') continue;
      ui_fill(x + c * 2 + 2, y + r * 2 + bob * 2 + 2, 2, 2, 0x000000);
    }
  }
  for (int r = 0; r < 11; r++) {
    const char *row = kFairy[f][r];
    for (int c = 0; row[c]; c++) {
      uint32_t col;
      switch (row[c]) {
        case 'w': col = 0xF8F8F8; break;
        case 'b': col = 0x98C8F8; break;
        case 'p': col = 0xF8A0C8; break;
        case 'y': col = 0xF8E070; break;
        case 'r': col = 0xE04848; break;
        default: continue;
      }
      ui_fill(x + c * 2, y + r * 2 + bob * 2, 2, 2, col);
    }
  }
}

void ui_heart(int x, int y, uint32_t c) {
  static const char *kHeart[7] = {
    ".##.##.",
    "#######",
    "#######",
    "#######",
    ".#####.",
    "..###..",
    "...#...",
  };
  for (int r = 0; r < 7; r++)
    for (int col = 0; col < 7; col++)
      if (kHeart[r][col] == '#') ui_fill(x + col, y + r, 1, 1, c);
}

// copies the 256x224 game picture to the canvas at 2x, optionally darkened (dim 0..255)
void ui_blit2x(const uint32_t *src, int sw, int sh, int dim) {
  int keep = 256 - dim;
  for (int y = 0; y < sh && y * 2 < CANVAS_H; y++) {
    uint32_t *d0 = g_canvas + (y * 2) * CANVAS_W;
    uint32_t *d1 = d0 + CANVAS_W;
    const uint32_t *s = src + y * sw;
    for (int x = 0; x < sw && x * 2 < CANVAS_W; x++) {
      uint32_t c = s[x];
      if (dim) c = ((((c & 0xff00ff) * keep) >> 8) & 0xff00ff) | ((((c & 0x00ff00) * keep) >> 8) & 0x00ff00);
      d0[x * 2] = d0[x * 2 + 1] = d1[x * 2] = d1[x * 2 + 1] = c;
    }
  }
}
